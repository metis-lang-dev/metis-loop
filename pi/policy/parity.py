def workspace():
    """The workspace: the first parent with .worlds/ (a worktree sits deeper)."""
    d = HERE
    while d != d.parent and not (d / ".worlds").is_dir():
        d = d.parent
    return d


def install(driver, w, out):
    """The loop's composition (DRIVER's catalog domains/) installed for game W under OUT (see the module's doc)."""
    from . import compose
    src = driver.root / "domains"
    comp = src / "composition.yaml"
    if not comp.exists():
        raise FileNotFoundError("no composition in %s (the refactor's compose move)" % src)
    out = Path(out)
    if out.exists():
        shutil.rmtree(out)
    dom = out / "domains"
    dom.mkdir(parents=True)
    members = _members(comp.read_text())
    for p in src.iterdir():
        if p.name in members or p.name == compose.DIRECTOR or p.name == "iface" or p.suffix in (".llp",) or p.name == "composition.yaml":
            (shutil.copytree if p.is_dir() else shutil.copy)(p, dom / p.name)
    inst = w.instance_text()
    (dom / "capacity.llp").write_text(compose.capacity_of(inst))
    dyn = driver.dynamic
    start = [l.strip() for l in inst.splitlines() if l.strip().startswith("#init ") and l.split()[1].split("(")[0] not in dyn]
    planner = members[0]
    prog = dom / planner / ("%s.llp" % planner)
    prog.write_text(prog.read_text().replace("#steps 6", "\n".join(start + ["#steps 6"])))
    log = dom / ".commands.jsonl"
    log.write_text("")
    meta = json.loads((w.pkg / "game.json").read_text())
    world_dir = Path(w.alf_host.__file__).resolve().parent
    shim = (world_dir / "package_host.py").read_text().replace("__WORLD__", str(world_dir))
    import yaml
    for m in members:
        man = yaml.safe_load((dom / m / "domain.yaml").read_text())
        observe = sorted(p for p, v in (man.get("shared") or {}).items() if v == "world-private")
        (dom / m / "game.json").write_text(json.dumps(dict(meta, spec=m, observe=observe, out=[], continues=True,
                                                            commands_log=str(log), verbs=True), indent=1))
        (dom / m / "alf_host.py").write_text(shim)
    (dom / compose.DIRECTOR / "pass_host.py").write_text(PASS_HOST)
    names = [compose.DIRECTOR] + members
    agent = workspace() / "metis-agent"
    # no member takes a person's intent (none has intent material), so Live reads the config's grammar; no turn uses it
    cfg = {"template": "gemma4", "stop_words": ["stop", "halt", "freeze", "quiet"],
           "intent": {"grammar": str(agent / "go" / "grammar" / "e11-next.gbnf")},
           "v3": {"prompt": [str(agent / "go" / "grammar" / "v3-orchestrator.txt")], "catalog": names, "loaded": names,
                  "serve": "active", "director": compose.DIRECTOR, "n_ctx": 16384, "tick_ms": 20,
                  "journal": str(out / ".run" / "journal.jsonl")},
           "domains": {"names": names, "case": "live", "seed": 1, "clocks": [{"domain": n, "n": 1} for n in names],
                       "trace": True, "records": str(out / ".run" / "records"), "tick": True, "consult": False}}
    (out / ".run").mkdir()
    (out / ".run" / "config.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False))
    return out


def _members(text):
    import re
    m = re.search(r"^specialists: \[([^\]]*)\]", text, re.M)
    return [x.strip() for x in m.group(1).split(",")] if m else []


def run_installed(root, out, ticks=400, quiet_s=3.0):
    """In metis-agent's venv: the installed composition under ROOT on Live with the tick, until the game is won or
    over, nothing new is sent for QUIET_S seconds, or TICKS ticks; → OUT.json {commands, ticks, end, error}."""
    import yaml
    from metis_agent.service import Live

    class NoModel:
        def sibling(self, n):
            return self

        def __getattr__(self, name):
            if name == "begin_dialog":
                return lambda *a, **k: 0
            raise RuntimeError("parity: no model (%s)" % name)
    root = Path(root)
    cfg = yaml.safe_load((root / ".run" / "config.yaml").read_text())
    frames = []
    res = {"commands": [], "ticks": 0, "end": None, "error": None}
    log = root / "domains" / ".commands.jsonl"
    try:
        import threading
        live = Live(cfg, NoModel(), emit=lambda ev, f, **kw: frames.append(dict(f, ev=ev)))
        live.journal.emit = lambda ev, f, **kw: frames.append(dict(f, ev=ev))
        for ag in live.agents.agents.values():               # no model: nothing narrated (nav_belief's run)
            ag.watch.blind = True
        threading.Thread(target=live.run, daemon=True, name="agent").start()
        live.started.set()
        last_n, last_t, t0 = 0, time.time(), time.time()
        while time.time() - t0 < ticks * 0.05 + 30:
            time.sleep(0.2)
            cmds = [json.loads(l)["command"] for l in log.read_text().splitlines() if l.strip()]
            end = next((f.get("state") for f in frames if f.get("ev") == "world/status" and f.get("state") in ("over", "done", "stuck", "asking")), None)
            if end:
                res["end"] = end
                break
            if len(cmds) != last_n:
                last_n, last_t = len(cmds), time.time()
            elif time.time() - last_t > quiet_s and cmds:
                res["end"] = "quiet"
                break
        live.stop.set()
        res["ticks"] = getattr(live, "beat", None)
    except Exception as e:                                  # noqa: BLE001 — the record says why
        res["error"] = "%s: %s" % (type(e).__name__, e)
    res["commands"] = [json.loads(l)["command"] for l in log.read_text().splitlines() if l.strip()] if log.exists() else []
    Path(out).write_text(json.dumps(res, indent=1, default=str))
    return res


def check(driver, games, label="parity", timeout=600):
    """Each game: the flat program's commands (the loop's runner), the tree's on Live (a child in metis-agent's
    venv), the same commands and the same win. → {"games": [...], "parity": bool}."""
    if driver.World.DOMAIN != "alf":
        return {"games": [], "parity": None, "why": WORLD_N_A}
    ws = workspace()
    agent_py = ws / "metis-agent" / "py"
    py = agent_py / ".venv" / "bin" / "python"
    rows = []
    for w in games:
        flat = w.act(driver._sync_tree("current", driver.base()), driver.cfg["act_steps"], seed=driver.seed)
        root = install(driver, w, driver.run / "parity" / label / w.iid)
        env = dict(os.environ, METIS_CATALOG=str(root), PYTHONPATH=os.pathsep.join([str(agent_py), str(HERE.parent)] + [p for p in os.environ.get("PYTHONPATH", "").split(os.pathsep) if p]),
                   METIS_ALF_PY=sys.executable, ALFWORLD_DATA=os.environ.get("ALFWORLD_DATA", str(ws / ".worlds" / "alfworld-data")))
        out = root / "tree.json"
        p = subprocess.run([str(py), "-m", "policy.parity", "run", str(root), str(out)], capture_output=True, text=True,
                           cwd=str(HERE.parent), env=env, timeout=timeout)
        tree = json.loads(out.read_text()) if out.exists() else {"commands": [], "error": (p.stderr or p.stdout)[-600:]}
        won_tree = _won(w, tree["commands"])
        rows.append({"iid": w.iid, "flat": flat["commands"], "tree": tree["commands"], "won_flat": bool(flat["won"]),
                     "won_tree": won_tree, "same": flat["commands"] == tree["commands"], "end": tree.get("end"),
                     "error": tree.get("error"), "choice": choice_point(driver, w, root)})
    # the architect's ruling: step-identical where the flat program is sequential; at a sampled choice the same plan
    # is accepted when the candidates and their weights there are the flat program's (an equal distribution, another
    # draw) and the tree wins what the flat program wins — different candidates are a routing difference
    ok = all((r["same"] or r["choice"]["same"]) and (r["won_tree"] or not r["won_flat"]) for r in rows)
    return {"games": rows, "parity": ok}


def choice_point(driver, w, root):
    """The planner's first choice, tree against flat: the rules the tree's planner can fire at the game's start (its
    installed program, its world-private reading of the flat program's start) that the flat base has too, their
    candidates and weights in each. → {"rules", "tree", "flat", "same"}: the same events with the same weights."""
    import yaml
    from metis.repl import Repl
    from .alfworld import kind_of, rules_of
    dom = Path(root) / "domains"
    planner = _members((dom / "composition.yaml").read_text())[0]
    tree_path = driver._sync_tree("current", driver.base())
    flat = Repl.open(w.into(tree_path) if Path(tree_path) != w.tree else w.path).shell
    man = yaml.safe_load((dom / planner / "domain.yaml").read_text())
    private = {p for p, v in (man.get("shared") or {}).items() if v == "world-private"}
    tsh = Repl.open(dom / planner / ("%s.llp" % planner)).shell
    tsh.counts = dict(tsh.counts, **{a: n for a, n in flat.counts.items() if n > 0 and kind_of(a) in private})
    cands = lambda sh: {sh.events_tbl[i][2].name: round(float(x), 9) for i, x in sh._candidates()}
    base_rules = {n for n, _ in rules_of(driver.base())}
    t = cands(tsh)
    rules = sorted({n.split("[")[0] for n in t} & base_rules)
    t = {n: x for n, x in t.items() if n.split("[")[0] in rules}
    f = {n: x for n, x in cands(flat).items() if n.split("[")[0] in rules}
    return {"rules": rules, "tree": t, "flat": f, "same": bool(rules) and t == f}


def _won(w, commands):
    """Whether COMMANDS, sent on a fresh game, win it."""
    w.reset()
    try:
        for c in commands:
            w.host._take(w.host.gym.call("step", command=c))
        return bool(w.host.won)
    finally:
        w.close()


